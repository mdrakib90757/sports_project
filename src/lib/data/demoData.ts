// Hydrate matches with teams, events, and lineups
export function getHydratedMatches(
  matches: Match[],
  teams: Team[],
  players: Player[],
  events: MatchEvent[],
  lineups: MatchLineupItem[]
): Match[] {
  const teamMap = new Map(teams.map((t) => [t.id, t]));
  const playerMap = new Map(players.map((p) => [p.id, p]));

  return matches.map((m) => {
    const homeTeam = teamMap.get(m.home_team_id);
    const awayTeam = teamMap.get(m.away_team_id);
    const matchEvents = events
      .filter((e) => e.match_id === m.id)
      .sort((a, b) => a.minute - b.minute)
      .map((e) => ({
        ...e,
        player: playerMap.get(e.player_id),
        assist_player: e.assist_player_id ? playerMap.get(e.assist_player_id) : undefined,
        sub_in_player: e.sub_in_player_id ? playerMap.get(e.sub_in_player_id) : undefined,
        team: teamMap.get(e.team_id),
      }));

    const matchLineups = lineups
      .filter((l) => l.match_id === m.id)
      .map((l) => ({
        ...l,
        player: playerMap.get(l.player_id),
      }));

    return {
      ...m,
      home_team: homeTeam,
      away_team: awayTeam,
      events: matchEvents,
      lineups: matchLineups,
    };
  });
}

